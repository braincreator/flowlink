        foreground: theme.colors.foreground,
        cursor: theme.colors.cursor,
        cursorAccent: theme.colors.cursorAccent,
        selectionBackground: theme.colors.selectionBackground,
        black: theme.colors.black,
        red: theme.colors.red,
